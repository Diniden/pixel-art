/**
 * `pixelBrushScale/hqxTable` — the 256 hq2x cases as DATA (plan 13, task 10;
 * MASTER D8, R3, R6).
 *
 * `max-lines` is an error at 400 code lines under `src/ui/**`, so the case
 * table lives here as one string per pattern and `hqx.ts` decodes it once at
 * module load. Nothing in this file is executed; a malformed entry throws in
 * the decoder, not here.
 *
 * ## Index
 *
 * The array index is the 8-bit "different neighbour" pattern of the 3×3
 * neighbourhood around the centre E:
 *
 * ```
 *   w1 w2 w3        bit 0 = w1   bit 1 = w2   bit 2 = w3   bit 3 = w4
 *   w4 E  w6        bit 4 = w6   bit 5 = w7   bit 6 = w8   bit 7 = w9
 *   w7 w8 w9
 * ```
 *
 * A bit is set when that neighbour is "different" from E (`hqx.ts` decides
 * what different means).
 *
 * ## Entry format
 *
 * `"TL|TR|BL|BR"` — one rule per output sub-pixel of the 2×2 block, in
 * row-major order. Each rule is either a **variant** or a **conditional**
 * `?k:A:B`: test whether corner `k`'s two edge neighbours are different
 * (`k` = 0 TL w4/w2, 1 TR w2/w6, 2 BL w8/w4, 3 BR w6/w8); if so apply
 * variant `A`, otherwise `B`. The tested corner is usually the rule's own
 * but not always — 40 rules look at a neighbouring corner's pair.
 *
 * A variant names a weighted blend over the centre E and the rule's corner
 * cells, where **p** is the edge neighbour BEFORE the corner going clockwise,
 * **d** the diagonal, **q** the edge neighbour AFTER it:
 *
 * ```
 *   TL: p = w4, d = w1, q = w2      TR: p = w2, d = w3, q = w6
 *   BL: p = w8, d = w7, q = w4      BR: p = w6, d = w9, q = w8
 * ```
 *
 * | variant | weights (E : p : q : d) | published macro          |
 * | ------- | ----------------------- | ------------------------ |
 * | 0       | 1 : 0 : 0 : 0           | copy E                   |
 * | 10      | 3 : 0 : 0 : 1           | Interp1(E, d)            |
 * | 11      | 3 : 1 : 0 : 0           | Interp1(E, p)            |
 * | 12      | 3 : 0 : 1 : 0           | Interp1(E, q)            |
 * | 20      | 2 : 1 : 1 : 0           | Interp2(E, p, q)         |
 * | 21      | 2 : 0 : 1 : 1           | Interp2(E, d, q)         |
 * | 22      | 2 : 1 : 0 : 1           | Interp2(E, d, p)         |
 * | 60      | 5 : 1 : 2 : 0           | Interp6(E, q, p)         |
 * | 61      | 5 : 2 : 1 : 0           | Interp6(E, p, q)         |
 * | 70      | 6 : 1 : 1 : 0           | Interp7(E, p, q)         |
 * | 90      | 2 : 3 : 3 : 0           | Interp9(E, p, q)         |
 * | 100     | 14 : 1 : 1 : 0          | Interp10(E, p, q)        |
 *
 * The rows were transcribed mechanically from the published hq2x case table
 * (Maxim Stepin's algorithm, as carried in the hqx reference implementation):
 * each `PIXELxx_v` macro became its variant number `v`, each
 * `if (Diff(w[a], w[b]))` became the corner whose pair (a, b) is. The
 * dihedral-symmetry suite in `__tests__/hqx.test.ts` is what proves the
 * transcription: a single wrong row breaks it.
 */

